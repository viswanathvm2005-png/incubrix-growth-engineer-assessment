import pytest

from engine.content_brief import ContentBrief, ContentFormat, Platform
from engine.generation_contract import (
    GeneratedDraft,
    GenerationRequest,
    GenerationResult,
    GenerationStatus,
)
from engine.generation_workflow import (
    GenerationWorkflow,
    describe_generation_result,
    run_generation,
)
from engine.mock_provider import MockGenerationProvider


def make_request(content_format=ContentFormat.TEXT_POST):
    brief = ContentBrief(
        brief_id="brief-workflow-test",
        campaign_objective="Test workflow integration",
        target_audience="Assessment reviewers",
        platform=Platform.LINKEDIN,
        content_format=content_format,
        source_ids=["source-workflow-test"],
        capability_ids=[],
        key_message="Explain the supplied message clearly",
        tone="Professional",
        call_to_action="Learn more",
        avoid_topics=[],
        requested_duration_seconds=(
            30 if content_format == ContentFormat.SHORT_VIDEO else None
        ),
        aspect_ratio=(
            "9:16" if content_format == ContentFormat.SHORT_VIDEO else None
        ),
    )
    return GenerationRequest(
        request_id="request-workflow-test",
        brief=brief,
        requested_draft_count=2,
        authorized_capability_ids=[],
    )


def test_workflow_runs_mock_provider():
    result = GenerationWorkflow(MockGenerationProvider()).run(make_request())

    assert result.status == GenerationStatus.SUCCESS
    assert len(result.drafts) == 2
    assert result.provider_name == "mock"


def test_convenience_function_runs_provider():
    result = run_generation(make_request(), MockGenerationProvider())

    assert result.brief_id == "brief-workflow-test"
    assert len(result.drafts) == 2


def test_workflow_validates_provider_result():
    class WrongBriefProvider:
        def generate(self, request):
            return GenerationResult(
                brief_id="some-other-brief",
                status=GenerationStatus.SUCCESS,
                drafts=[
                    GeneratedDraft(
                        draft_id="draft-wrong-brief",
                        content_format=request.brief.content_format,
                        angle="Test angle",
                        hook="Test hook",
                        caption="Test caption",
                        call_to_action="Learn more",
                    )
                ],
            )

    with pytest.raises(ValueError, match="brief_id does not match"):
        GenerationWorkflow(WrongBriefProvider()).run(make_request())


def test_workflow_does_not_hide_provider_errors():
    class BrokenProvider:
        def generate(self, request):
            raise RuntimeError("Simulated provider failure")

    with pytest.raises(RuntimeError, match="Simulated provider failure"):
        GenerationWorkflow(BrokenProvider()).run(make_request())


def test_result_summary_is_serializable_and_explicit():
    result = GenerationWorkflow(MockGenerationProvider()).run(make_request())
    summary = describe_generation_result(result)

    assert summary["brief_id"] == "brief-workflow-test"
    assert summary["status"] == "success"
    assert summary["draft_count"] == 2
    assert summary["provider_name"] == "mock"
    assert summary["is_success"] is True
    assert any("MOCK OUTPUT ONLY" in warning for warning in summary["warnings"])


def test_video_request_flows_through_workflow():
    result = GenerationWorkflow(MockGenerationProvider()).run(
        make_request(ContentFormat.SHORT_VIDEO)
    )

    assert all(draft.video_script for draft in result.drafts)


def test_workflow_does_not_claim_mock_output_is_real_ai():
    result = GenerationWorkflow(MockGenerationProvider()).run(make_request())

    assert result.provider_name == "mock"
    assert any("not generated by an AI model" in warning for warning in result.warnings)


def test_workflow_adds_factual_language_warning_without_changing_draft():
    request = make_request()

    class TestingLanguageProvider:
        def generate(self, request):
            return GenerationResult(
                brief_id=request.brief.brief_id,
                status=GenerationStatus.SUCCESS,
                warnings=["Existing provider warning"],
                drafts=[
                    GeneratedDraft(
                        draft_id="draft-testing-language",
                        content_format=request.brief.content_format,
                        angle="Testing example",
                        hook="We tested the workflow",
                        caption="This assessment demonstrates the result.",
                        call_to_action="Learn more",
                    )
                ],
            )

    result = GenerationWorkflow(TestingLanguageProvider()).run(request)

    assert result.drafts[0].hook == "We tested the workflow"
    assert result.drafts[0].caption == "This assessment demonstrates the result."
    assert "Existing provider warning" in result.warnings
    assert any("Potentially unsupported testing/result language" in w for w in result.warnings)


def test_workflow_keeps_clean_draft_without_factual_language_warning():
    request = make_request()

    class EducationalProvider:
        def generate(self, request):
            return GenerationResult(
                brief_id=request.brief.brief_id,
                status=GenerationStatus.SUCCESS,
                warnings=["Existing provider warning"],
                drafts=[
                    GeneratedDraft(
                        draft_id="draft-educational",
                        content_format=request.brief.content_format,
                        angle="Educational explanation",
                        hook="Start with one clear question",
                        caption="Explain the idea, give an example, and invite discussion.",
                        call_to_action="Share your perspective",
                    )
                ],
            )

    result = GenerationWorkflow(EducationalProvider()).run(request)

    assert result.warnings == ["Existing provider warning"]

